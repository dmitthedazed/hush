/** Both tables' functions of one v2 headset. */
data class V2Functions(val t1: Set<Int>, val t2: Set<Int> = emptySet()) {
    fun has(f: FunctionType1) = f.code in t1
    fun has(f: FunctionType2) = f.code in t2
    fun any(vararg f: FunctionType1) = f.any(::has)
    fun any(vararg f: FunctionType2) = f.any(::has)

    /**
     * The v1 FunctionType codes with the same meaning, for the UI and controller, which ask `has(v1 FunctionType)`.
     * Only functions Hush drives over v2 are mapped (no firmware update, NC optimizer or adaptive sound yet);
     * general settings 1–4 keep their raw codes (0xD1..0xD4), as on v1.
     */
    fun v1Equivalents(): Set<Int> = buildSet {
        fun map(v1: V1, vararg v2: FunctionType1) { if (any(*v2)) add(v1.code) }
        map(V1.CODEC_INDICATOR, FunctionType1.CODEC_INDICATOR)
        map(V1.BLE_SETUP, FunctionType1.BLE_SETUP)
        map(V1.LEFT_RIGHT_CONNECTION_STATUS, FunctionType1.CONNECTION_STATUS)
        map(V1.LEFT_RIGHT_BATTERY_LEVEL, FunctionType1.LEFT_RIGHT_BATTERY_LEVEL_INDICATOR, FunctionType1.LR_BATTERY_LEVEL_WITH_THRESHOLD)
        map(V1.CRADLE_BATTERY_LEVEL, FunctionType1.CRADLE_BATTERY_LEVEL_INDICATOR, FunctionType1.CRADLE_BATTERY_LEVEL_WITH_THRESHOLD)
        map(V1.POWER_OFF, FunctionType1.POWER_OFF)
        map(V1.TANDEM_KEEP_ALIVE, FunctionType1.TANDEM_KEEP_ALIVE)
        map(V1.PRESET_EQ, FunctionType1.PRESET_EQ, FunctionType1.PRESET_EQ_AND_ERRORCODE, FunctionType1.PRESET_EQ_AND_ULT_MODE)
        map(V1.PRESET_EQ_NONCUSTOMIZABLE, FunctionType1.PRESET_EQ_NON_CUSTOMIZABLE)
        map(V1.EBB, FunctionType1.EBB)
        if (Update.typeFor(this@V2Functions) != null) add(V1.FW_UPDATE.code)
        map(V1.NC_OPTIMIZER, FunctionType1.NC_OPTIMIZER_PERSONAL_BAROMETRIC, FunctionType1.NC_OPTIMIZER_PERSONAL,
            FunctionType1.NC_OPTIMIZER_BAROMETRIC)
        when (NcAsmV2.typeFor(this@V2Functions)?.kind) {
            com.occaecat.hush.mdr.NcAsmKind.NC -> add(V1.NOISE_CANCELLING.code)
            com.occaecat.hush.mdr.NcAsmKind.ASM -> add(V1.AMBIENT_SOUND_MODE.code)
            com.occaecat.hush.mdr.NcAsmKind.NC_ASM -> add(V1.NOISE_CANCELLING_AND_AMBIENT_SOUND_MODE.code)
            null -> {}
        }
        if (Play.supported(this@V2Functions)) add(V1.PLAYBACK_CONTROLLER.code)
        for (gs in GeneralSettings.ids) if (gs in t1) add(gs)
        map(V1.CONNECTION_MODE, FunctionType1.CONNECTION_MODE_SOUND_QUALITY_CONNECTION_QUALITY,
            FunctionType1.CONNECTION_MODE_SOUND_QUALITY_SOUND_WITH_LDAC_STATUS_QUALITY_CONNECTION_QUALITY,
            FunctionType1.CONNECTION_MODE_CLASSIC_AUDIO_LE_AUDIO)
        map(V1.UPSCALING, FunctionType1.UPSCALING_AUTO_OFF, FunctionType1.UPSCALING_AUTO_OFF_WITH_STATUS_DISABLE_REASON)
        map(V1.VIBRATOR, FunctionType1.VIBRATOR_ON_OFF)
        map(V1.CONTROL_BY_WEARING, FunctionType1.PLAYBACK_CONTROL_BY_WEARING_REMOVING_HEADPHONE_ON_OFF)
        map(V1.AUTO_POWER_OFF, FunctionType1.AUTO_POWER_OFF, FunctionType1.AUTO_POWER_OFF_WITH_WEARING_DETECTION)
        map(V1.SMART_TALKING_MODE, FunctionType1.SMART_TALKING_MODE_TYPE1, FunctionType1.SMART_TALKING_MODE_TYPE2)
        map(V1.ASSIGNABLE_SETTINGS, FunctionType1.ASSIGNABLE_SETTING, FunctionType1.ASSIGNABLE_SETTING_WITH_LIMITATION)
        if (Peripheral.typeFor(this@V2Functions) != null) add(V1.PAIRING_DEVICE_MANAGEMENT_CLASSIC_BT.code)
        if (VoiceGuidance.typeFor(this@V2Functions) != null) add(V1.VOICE_GUIDANCE.code)
    }
}
